#!/usr/bin/env python3
"""Builds the page the native backends load: boron.css + boron.js -> ../boron_page.h

  gen_page.py          rewrite ../boron_page.h
  gen_page.py --html   print the page instead (used by the tests)
  gen_page.py --check  exit 1 if ../boron_page.h is out of date
"""
import sys
from pathlib import Path

here = Path(__file__).resolve().parent


def page():
    css = (here / "boron.css").read_text()
    js = (here / "boron.js").read_text()
    return ("<!doctype html>\n<html><head><meta charset=\"utf-8\">\n"
            "<style>\n" + css + "</style>\n<style id=\"bn-user\"></style>\n"
            "</head><body><div id=\"bn-root\"></div>\n<script>\n" + js + "</script>\n</body></html>\n")


def header(text):
    out = ["// Generated by native/page/gen_page.py from boron.css and boron.js. Do not edit.",
           "#pragma once", "static const char BN_PAGE[] ="]
    for line in text.splitlines(keepends=True):
        esc = line.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n")
        out.append("    \"" + esc + "\"")
    out[-1] += ";"
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    target = here.parent / "boron_page.h"
    if "--html" in sys.argv:
        sys.stdout.write(page())
    elif "--check" in sys.argv:
        ok = target.exists() and target.read_text() == header(page())
        if not ok:
            print(f"{target} is out of date: run boron/native/page/gen_page.py")
        sys.exit(0 if ok else 1)
    else:
        target.write_text(header(page()))
